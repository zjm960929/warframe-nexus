function compactName(value) {
  return String(value || '').toLowerCase().replace(/[^a-z0-9\u4e00-\u9fff]/g, '');
}

/** Find a Riven-capable weapon by an OCR name, preferring exact names. */
export function findRivenWeapon(name) {
  const needle = compactName(name);
  if (!needle) return null;
  let best = null;
  for (const weapon of RIVEN_WEAPONS) {
    for (const candidate of [weapon.zh, weapon.en]) {
      const haystack = compactName(candidate);
      if (!haystack) continue;
      let score = 0;
      if (haystack === needle) score = 1000;
      else if (haystack.includes(needle) || needle.includes(haystack)) {
        score = 100 + Math.min(haystack.length, needle.length);
      } else {
        const grams = new Set();
        for (let i = 0; i < needle.length - 1; i += 1) grams.add(needle.slice(i, i + 2));
        let hits = 0;
        for (let i = 0; i < haystack.length - 1; i += 1) if (grams.has(haystack.slice(i, i + 2))) hits += 1;
        const similarity = hits / Math.max(1, grams.size + haystack.length - 1);
        if (similarity >= 0.5) score = similarity * 100;
      }
      if (!best || score > best.score) best = { ...weapon, score };
    }
  }
  return best && best.score >= 50 ? best : null;
}
